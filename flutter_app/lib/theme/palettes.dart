PaletteTokens resolvePaletteTokens(PaletteId id, bool isDark) {
  final preset = kPalettePresets.firstWhere(
    (p) => p.id == id,
    orElse: () => kPalettePresets.first,
  );
  return isDark ? preset.dark : preset.light;
}

ThemeData buildAppTheme(PaletteTokens tokens, bool isDark) {
  final scheme = ColorScheme(
    brightness: isDark ? Brightness.dark : Brightness.light,
    primary: tokens.primary,
    onPrimary: tokens.primaryFg,
    secondary: tokens.accent,
    onSecondary: tokens.accentFg,
    error: const Color(0xFFDC2626),
    onError: Colors.white,
    surface: tokens.bgSurface,
    onSurface: tokens.textPrimary,
  );

  return ThemeData(
    useMaterial3: true,
    colorScheme: scheme,
    scaffoldBackgroundColor: tokens.bgCanvas,
    cardColor: tokens.bgSurface,
    dividerColor: tokens.borderSubtle,
    appBarTheme: AppBarTheme(
      backgroundColor: tokens.bgSurface,
      foregroundColor: tokens.textPrimary,
      elevation: 0,
      scrolledUnderElevation: 1,
    ),
    cardTheme: CardThemeData(
      color: tokens.bgSurface,
      elevation: 0,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(18),
        side: BorderSide(color: tokens.borderSubtle),
      ),
    ),
    inputDecorationTheme: InputDecorationTheme(
      filled: true,
      fillColor: tokens.bgSubtle,
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(12),
        borderSide: BorderSide(color: tokens.borderSubtle),
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(12),
        borderSide: BorderSide(color: tokens.borderSubtle),
      ),
      focusedBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(12),
        borderSide: BorderSide(color: tokens.primary, width: 1.5),
      ),
    ),
    filledButtonTheme: FilledButtonThemeData(
      style: FilledButton.styleFrom(
        backgroundColor: tokens.primary,
        foregroundColor: tokens.primaryFg,
        minimumSize: const Size(48, 46),
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
      ),
    ),
  );
}
